"""
Profile every raw dataset (schema, row count, nulls, dtypes, date/geo ranges)
without loading full files into memory. Uses DuckDB's lazy CSV scanning, which
streams/aggregates rather than materializing whole files in Python.

Output: data/metadata/profiles.json + data/metadata/inventory.md
Safe to re-run: overwrites its own output, never touches data/raw.
"""
import json
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
META = ROOT / "data" / "metadata"
META.mkdir(parents=True, exist_ok=True)

CSV_FILES = sorted(RAW.glob("*.csv"))

# Columns worth range-profiling when present, by semantic role.
TIMESTAMP_COLS = ["timestamp", "start_time", "end_time"]
GEO_COLS = [("lat", "lon"), ("x", "y")]


def profile_csv(con, path: Path) -> dict:
    tbl = f"read_csv_auto('{path.as_posix()}', SAMPLE_SIZE=-1)"
    schema = con.execute(f"DESCRIBE SELECT * FROM {tbl}").fetchall()
    columns = [{"name": r[0], "type": r[1]} for r in schema]
    col_names = [c["name"] for c in columns]

    row_count = con.execute(f"SELECT count(*) FROM {tbl}").fetchone()[0]

    null_counts = {}
    for c in col_names:
        n = con.execute(f'SELECT count(*) FROM {tbl} WHERE "{c}" IS NULL').fetchone()[0]
        if n:
            null_counts[c] = n

    quoted_cols = ", ".join('"{}"'.format(c) for c in col_names)
    dup_count = con.execute(
        f"SELECT count(*) - count(DISTINCT ({quoted_cols})) FROM {tbl}"
    ).fetchone()[0]

    date_range = {}
    for c in TIMESTAMP_COLS:
        if c in col_names:
            lo, hi = con.execute(f'SELECT min("{c}"), max("{c}") FROM {tbl}').fetchone()
            date_range[c] = {"min": str(lo), "max": str(hi)}

    geo_range = {}
    for lon_lat in GEO_COLS:
        if all(c in col_names for c in lon_lat):
            a, b = lon_lat
            (a_lo, a_hi, b_lo, b_hi) = con.execute(
                f'SELECT min("{a}"), max("{a}"), min("{b}"), max("{b}") FROM {tbl}'
            ).fetchone()
            geo_range[f"{a}/{b}"] = {a: [a_lo, a_hi], b: [b_lo, b_hi]}

    numeric_types = {"BIGINT", "DOUBLE", "INTEGER", "HUGEINT", "DECIMAL"}
    negative_counts = {}
    for col in columns:
        if col["type"] in numeric_types and col["name"] not in ("lat", "lon", "x", "y", "grade_pct"):
            n = con.execute(f'SELECT count(*) FROM {tbl} WHERE "{col["name"]}" < 0').fetchone()[0]
            if n:
                negative_counts[col["name"]] = n

    return {
        "file": path.name,
        "size_bytes": path.stat().st_size,
        "rows": row_count,
        "columns": columns,
        "null_counts": null_counts,
        "full_row_duplicate_count": dup_count,
        "negative_value_counts": negative_counts,
        "timestamp_ranges": date_range,
        "geo_ranges": geo_range,
    }


def main():
    con = duckdb.connect()
    profiles = []
    for path in CSV_FILES:
        print(f"Profiling {path.name} ...")
        profiles.append(profile_csv(con, path))

    (META / "profiles.json").write_text(json.dumps(profiles, indent=2, default=str))

    lines = [
        "# Dataset Inventory (auto-generated by scripts/inspect_datasets.py)",
        "",
        "| Dataset | Rows | Columns | Size | Nulls (cols affected) | Duplicate rows | Negative-value cols |",
        "|---|---|---|---|---|---|---|",
    ]
    for p in profiles:
        lines.append(
            f"| {p['file']} | {p['rows']:,} | {len(p['columns'])} | {p['size_bytes']:,} B | "
            f"{len(p['null_counts'])} | {p['full_row_duplicate_count']} | {len(p['negative_value_counts'])} |"
        )
    (META / "inventory.md").write_text("\n".join(lines) + "\n")
    print(f"\nWrote {META / 'profiles.json'} and {META / 'inventory.md'}")


if __name__ == "__main__":
    main()
